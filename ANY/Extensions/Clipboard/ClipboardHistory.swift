import AppKit
import Observation

struct ClipboardEntry: Codable, Identifiable, Equatable {
    let id: UUID
    let text: String
    let date: Date
    let sourceApp: String?
}

/// Polls the general pasteboard and keeps a persisted list of recent text entries.
@Observable
final class ClipboardHistory {
    private(set) var entries: [ClipboardEntry] = []

    @ObservationIgnored private let fileURL: URL
    @ObservationIgnored private let preferences: ClipboardPreferences
    @ObservationIgnored private var pollTask: Task<Void, Never>?
    @ObservationIgnored private var lastChangeCount = NSPasteboard.general.changeCount

    private static let pollInterval = Duration.milliseconds(500)
    /// Markers used by password managers and other apps for content that shouldn't be recorded.
    private static let ignoredTypes: Set<NSPasteboard.PasteboardType> = [
        .init("org.nspasteboard.ConcealedType"),
        .init("org.nspasteboard.TransientType"),
        .init("org.nspasteboard.AutoGeneratedType"),
        .init("com.agilebits.onepassword"),
    ]

    init(fileURL: URL, preferences: ClipboardPreferences) {
        self.fileURL = fileURL
        self.preferences = preferences
        load()
        trimToLimit()
    }

    func startMonitoring() {
        guard pollTask == nil else { return }
        lastChangeCount = NSPasteboard.general.changeCount
        pollTask = Task { [weak self] in
            while !Task.isCancelled {
                try? await Task.sleep(for: Self.pollInterval)
                self?.poll()
            }
        }
    }

    func stopMonitoring() {
        pollTask?.cancel()
        pollTask = nil
    }

    func remove(_ id: UUID) {
        entries.removeAll { $0.id == id }
        save()
    }

    func removeAll() {
        entries.removeAll()
        save()
    }

    func trimToLimit() {
        let limit = preferences.historyLimit
        guard entries.count > limit else { return }
        entries.removeLast(entries.count - limit)
        save()
    }

    private func poll() {
        let pasteboard = NSPasteboard.general
        guard !Pasteboard.isBorrowed, pasteboard.changeCount != lastChangeCount else { return }
        lastChangeCount = pasteboard.changeCount
        guard lastChangeCount != Pasteboard.restoredChangeCount else { return }

        let types = Set(pasteboard.types ?? [])
        if preferences.ignoresSensitiveContent && !types.isDisjoint(with: Self.ignoredTypes) { return }
        guard let text = pasteboard.string(forType: .string),
              !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty
        else { return }

        entries.removeAll { $0.text == text }
        entries.insert(
            ClipboardEntry(
                id: UUID(),
                text: text,
                date: .now,
                sourceApp: NSWorkspace.shared.frontmostApplication?.localizedName
            ),
            at: 0
        )
        save()
        trimToLimit()
    }

    private func load() {
        guard let data = try? Data(contentsOf: fileURL),
              let decoded = try? JSONDecoder().decode([ClipboardEntry].self, from: data)
        else { return }
        entries = decoded
    }

    private func save() {
        guard let data = try? JSONEncoder().encode(entries) else { return }
        try? data.write(to: fileURL, options: [.atomic, .completeFileProtection])
    }
}
